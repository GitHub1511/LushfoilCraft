"""Flat item sprites used by block drops (coal, diamond, raw ores...): item_<name>.png + item_<name>_m.png (opacity mask), 8x nearest.
Usage: python -I tools/make_items.py <client jar> ."""
import os, sys, zipfile
sys.path.insert(0, os.path.dirname(__file__))
from make_assets import png_decode, png_encode, upscale, first_frame
ITEMS = ["coal", "diamond", "emerald", "lapis_lazuli", "redstone", "raw_iron", "raw_copper", "raw_gold", "quartz", "gold_nugget", "flint",
         "clay_ball", "snowball", "glowstone_dust", "prismarine_crystals", "amethyst_shard", "stick", "wheat_seeds", "apple", "bread", "cooked_beef", "shears"]
ITEMS += [f"{t}_{k}" for t in ("wooden", "stone", "iron", "golden", "diamond", "netherite") for k in ("pickaxe", "axe", "shovel", "hoe", "sword")]
jar, out = sys.argv[1], sys.argv[2]
z = zipfile.ZipFile(jar)
import re
for nm in z.namelist():                      # every flat item sprite (frame-numbered clocks/compasses, overlays and empty-slot hints skipped)
    m = re.match(r"assets/minecraft/textures/item/([a-z0-9_]+)\.png$", nm)
    if not m: continue
    n = m.group(1)
    if n.endswith("_overlay") or n.startswith("empty_") or re.search(r"_\d\d$", n) or n in ITEMS: continue
    ITEMS.append(n)
for n in ITEMS:
    w, h, px = png_decode(z.read(f"assets/minecraft/textures/item/{n}.png"))
    px = first_frame(px) if h > w else px
    rgb = [[(p[0], p[1], p[2], 255) for p in r] for r in px]
    mask = [[(p[3], p[3], p[3], 255) for p in r] for r in px]
    open(os.path.join(out, "textures", f"item_{n}.png"), "wb").write(png_encode(upscale(rgb, 8)))
    open(os.path.join(out, "textures", f"icon_item_{n}.png"), "wb").write(png_encode(upscale(px, 8)))     # RGBA, for the hotbar
    open(os.path.join(out, "textures", f"item_{n}_m.png"), "wb").write(png_encode(upscale(mask, 8)))
print(len(ITEMS), "items")

# block-breaking crack overlays (10 stages): colour + opacity mask for the cut-out material
for n in range(10):
    w, h, px = png_decode(z.read(f"assets/minecraft/textures/block/destroy_stage_{n}.png"))
    rgb = [[(p[0], p[1], p[2], 255) for p in r] for r in px]
    mask = [[(255 if p[3] > 40 else 0,) * 3 + (255,) for p in r] for r in px]
    open(os.path.join(out, "textures", f"crack_{n}.png"), "wb").write(png_encode(upscale(rgb, 8)))
    open(os.path.join(out, "textures", f"crack_{n}_m.png"), "wb").write(png_encode(upscale(mask, 8)))
print("cracks")

ids = sorted(set(ITEMS))
with open(os.path.join(out, "Scripts", "items.lua"), "w") as f:
    f.write("-- generated by tools/make_items.py: ids of every flat Minecraft item sprite\n")
    f.write("return {\n")
    for n in ids: f.write('  "%s",\n' % n)
    f.write("}\n")
print("items.lua:", len(ids))
